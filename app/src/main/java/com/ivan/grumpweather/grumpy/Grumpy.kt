/** Во что превращается погода, когда на неё смотрит ворчливый мудак. */
enum class Mood {
    THUNDER, BLIZZARD, SNOW, ICE, DOWNPOUR, RAIN, DRIZZLE, FOG, STORM_WIND,
    EXTREME_COLD, COLD, FROSTY, HAMSIN, INFERNO, SAUNA, HOT, SWAMP,
    DREARY, CHILLY, MILD, NICE
}

object Grumpy {

    private val THUNDER_CODES = setOf(95, 96, 99)
    private val SNOW_CODES = setOf(71, 73, 75, 77, 85, 86)
    private val ICE_CODES = setOf(56, 57, 66, 67)
    private val HEAVY_RAIN_CODES = setOf(65, 82)
    private val RAIN_CODES = setOf(61, 63, 80, 81)
    private val DRIZZLE_CODES = setOf(51, 53, 55)
    private val FOG_CODES = setOf(45, 48)

    private val WET = setOf(
        Mood.THUNDER, Mood.BLIZZARD, Mood.SNOW, Mood.ICE, Mood.DOWNPOUR,
        Mood.RAIN, Mood.DRIZZLE, Mood.FOG, Mood.SWAMP, Mood.SAUNA
    )

    /**
     * temp — реальная температура, feels — «ощущается как», wind/gust — м/с,
     * humidity — %, precip — мм за последний час (0, если не знаем).
     */
    fun classify(
        code: Int,
        temp: Double,
        feels: Double,
        humidity: Int,
        wind: Double,
        gust: Double,
        precip: Double = 0.0,
    ): Mood = when {
        code in THUNDER_CODES -> Mood.THUNDER
        code in SNOW_CODES -> if (wind >= 10 || gust >= 17) Mood.BLIZZARD else Mood.SNOW
        code in ICE_CODES -> Mood.ICE
        code in HEAVY_RAIN_CODES || precip >= 5.0 -> Mood.DOWNPOUR
        code in RAIN_CODES -> Mood.RAIN
        code in DRIZZLE_CODES -> Mood.DRIZZLE
        code in FOG_CODES -> Mood.FOG
        wind >= 13 || gust >= 22 -> Mood.STORM_WIND
        feels <= -20 -> Mood.EXTREME_COLD
        feels <= -5 -> Mood.COLD
        feels <= 3 -> Mood.FROSTY
        temp >= 30 && humidity < 30 && wind >= 5 -> Mood.HAMSIN
        feels >= 36 -> Mood.INFERNO
        temp >= 26 && humidity >= 65 -> Mood.SAUNA
        feels >= 28 -> Mood.HOT
        humidity >= 88 -> Mood.SWAMP
        code == 3 || (code == 2 && temp < 18) -> Mood.DREARY
        feels < 12 -> Mood.CHILLY
        feels < 20 -> Mood.MILD
        else -> Mood.NICE
    }

    fun headline(mood: Mood, isDay: Boolean, rnd: Random): String =
        if (!isDay && mood == Mood.NICE) NICE_NIGHT.random(rnd)
        else HEADLINES.getValue(mood).random(rnd)

    fun sub(mood: Mood, rnd: Random): String = SUBS.getValue(mood).random(rnd)

    fun short(mood: Mood, rnd: Random): String = SHORT.getValue(mood).random(rnd)

    fun loading(rnd: Random = Random): String = LOADING.random(rnd)

    /** Дополнительные поводы поныть, которые не вошли в главную фразу. */
    fun extras(
        temp: Double, feels: Double, humidity: Int, wind: Double, gust: Double,
        isDay: Boolean, mood: Mood,
    ): List<String> {
        val list = mutableListOf<String>()
        if (wind >= 8 && mood != Mood.STORM_WIND && mood != Mood.BLIZZARD) list += "💨 ветер в ебало"
        if (gust >= 15 && mood != Mood.STORM_WIND && mood != Mood.BLIZZARD) list += "🌪 порывы, сука"
        if (humidity >= 80 && mood !in WET) list += "💧 сырость ебучая"
        if (humidity <= 25) list += "🏜 сухо, губы трескаются"
        if (feels - temp >= 3) list += "🥵 по ощущениям ещё хуже"
        if (temp - feels >= 4) list += "🥶 по ощущениям ещё холоднее"
        if (!isDay) list += "🌚 и ещё темно, бля"
        return list
    }

